//! Exact `worldname` PathID 8 rectangle order used by
//! `WorldDataContainer.ReceivePtDongName`.

#[derive(Clone, Copy)]
pub(super) struct LegacyWorldNameArea {
    pub x: f32,
    pub z: f32,
    pub width: f32,
    pub height: f32,
    pub district: &'static str,
    pub zone: &'static str,
}

impl LegacyWorldNameArea {
    const fn tile(x: f32, z: f32, district: &'static str, zone: &'static str) -> Self {
        Self {
            x,
            z,
            width: 512.0,
            height: 512.0,
            district,
            zone,
        }
    }

    const fn rect(
        x: f32,
        z: f32,
        width: f32,
        height: f32,
        district: &'static str,
        zone: &'static str,
    ) -> Self {
        Self {
            x,
            z,
            width,
            height,
            district,
            zone,
        }
    }

    pub fn contains(self, x: f32, z: f32) -> bool {
        x >= self.x && x < self.x + self.width && z >= self.z && z < self.z + self.height
    }
}

