#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub struct ResurrectInventorySlot {
    pub column: i32,
    pub empty: bool,
    pub item_type: i32,
    /// `None` means the GeneralItem table lookup did not resolve.
    pub general_item_type: Option<i32>,
}

/// Mirrors the clean inventory scan, including its "last matching column
/// wins" behavior.
#[must_use]
pub fn clean_resurrection_item_slot(
    slots: impl IntoIterator<Item = ResurrectInventorySlot>,
) -> Option<i32> {
    slots
        .into_iter()
        .filter(|slot| !slot.empty && slot.item_type == 7 && slot.general_item_type == Some(10))
        .map(|slot| slot.column)
        .last()
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Resource)]
pub struct ResurrectUiContext {
    pub ready_for_play: bool,
    pub player_available: bool,
    pub system_popup_active: bool,
    pub skill_icon_back_available: bool,
    pub phoenix_group_icon_available: bool,
    pub phoenix_self_icon_available: bool,
    pub phoenix_group_skill: bool,
    pub phoenix_self_skill_bit_16: bool,
    pub resurrection_item_slot: Option<i32>,
    /// Typed boundary for clean `GetXCom()`. `Some(0)` is a valid legacy
    /// no-match result; `None` means FFOne has not resolved the dependency.
    pub nearest_xcom_index: Option<i32>,
}

impl ResurrectUiContext {
    #[must_use]
    pub const fn clean_controls_gate_open(self) -> bool {
        // The clean code checks GroupIcon even for GO and self-revive. It does
        // not include PhoenixSelfIcon in this outer gate.
        self.player_available && self.skill_icon_back_available && self.phoenix_group_icon_available
    }

    #[must_use]
    pub const fn phoenix_choice(self) -> Option<ResurrectChoice> {
        if self.phoenix_group_skill {
            Some(ResurrectChoice::PhoenixGroup)
        } else if self.phoenix_self_skill_bit_16 {
            Some(ResurrectChoice::PhoenixSelf)
        } else {
            None
        }
    }

    /// Clean paint order. `UseItem`, when present, is last and overlaps the
    /// Phoenix slot.
    #[must_use]
    pub const fn choice_draw_order(self) -> [Option<ResurrectChoice>; 3] {
        if !self.clean_controls_gate_open() {
            return [None, None, None];
        }
        [
            Some(ResurrectChoice::NearestResurrectEm),
            self.phoenix_choice(),
            if self.resurrection_item_slot.is_some() {
                Some(ResurrectChoice::UseItem)
            } else {
                None
            },
        ]
    }

    #[must_use]
    pub fn choice_is_visible(self, choice: ResurrectChoice) -> bool {
        self.choice_draw_order().contains(&Some(choice))
    }

    #[must_use]
    pub fn topmost_choice_at(self, local_point: Vec2) -> Option<ResurrectChoice> {
        self.choice_draw_order()
            .into_iter()
            .rev()
            .flatten()
            .find(|choice| choice.rect().contains(local_point))
    }
}

