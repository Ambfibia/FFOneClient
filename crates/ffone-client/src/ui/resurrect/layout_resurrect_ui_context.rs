#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct ResurrectUiRect {
    pub x: f32,
    pub y: f32,
    pub width: f32,
    pub height: f32,
}

impl ResurrectUiRect {
    #[must_use]
    pub const fn new(x: f32, y: f32, width: f32, height: f32) -> Self {
        Self {
            x,
            y,
            width,
            height,
        }
    }

    #[must_use]
    pub fn contains(self, point: Vec2) -> bool {
        point.x >= self.x
            && point.x < self.x + self.width
            && point.y >= self.y
            && point.y < self.y + self.height
    }

    pub(super) fn node(self) -> Node {
        Node {
            position_type: PositionType::Absolute,
            left: px(self.x),
            top: px(self.y),
            width: px(self.width),
            height: px(self.height),
            ..default()
        }
    }
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ResurrectUiLayout {
    pub viewport: Vec2,
    pub pivot: Vec2,
    pub dialog_left: f32,
    pub dialog_top: f32,
    pub source_size: Vec2,
    pub scale: f32,
    pub visual_rect: ResurrectUiRect,
}

#[must_use]
pub fn clean_resurrect_ui_scale(viewport_height: f32) -> f32 {
    if !viewport_height.is_finite() || viewport_height <= 0.0 {
        return 1.0;
    }
    (viewport_height / RESURRECT_REFERENCE_HEIGHT * RESURRECT_UI_SCALE_NUDGE).max(1.0)
}

#[must_use]
pub fn resurrect_ui_layout(viewport: Vec2, ui_scale: f32) -> ResurrectUiLayout {
    let width = legacy_screen_extent(viewport.x);
    let height = legacy_screen_extent(viewport.y);
    let viewport = Vec2::new(width as f32, height as f32);
    let pivot = Vec2::new((width / 2) as f32, (height / 2) as f32);
    let scale = valid_ui_scale(ui_scale);
    let source_size = Vec2::new(RESURRECT_WINDOW_RECT.width, RESURRECT_WINDOW_RECT.height);
    let dialog_left = ((width - source_size.x as i32) / 2) as f32;
    let dialog_top = ((height - source_size.y as i32) / 2) as f32;
    let visual_size = source_size * scale;

    ResurrectUiLayout {
        viewport,
        pivot,
        dialog_left,
        dialog_top,
        source_size,
        scale,
        visual_rect: ResurrectUiRect::new(
            pivot.x - visual_size.x * 0.5,
            pivot.y - visual_size.y * 0.5,
            visual_size.x,
            visual_size.y,
        ),
    }
}

pub(super) fn valid_ui_scale(value: f32) -> f32 {
    if value.is_finite() && value > 0.0 {
        value
    } else {
        1.0
    }
}

